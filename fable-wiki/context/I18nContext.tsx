import React, { createContext, useContext, useState, useCallback, useEffect } from 'react';

export type Lang = 'fr' | 'en';

/** Translation object — fr and en required */
export type Translations = { fr: string; en: string } & { [key: string]: string };

const SUPPORTED_LANGS: Lang[] = ['fr', 'en'];

function detectBrowserLang(): Lang {
  const stored = localStorage.getItem('fable-lang');
  if (stored && SUPPORTED_LANGS.includes(stored as Lang)) return stored as Lang;
  const nav = navigator.language || (navigator as any).userLanguage || 'en';
  const code = nav.split('-')[0].toLowerCase();
  if (SUPPORTED_LANGS.includes(code as Lang)) return code as Lang;
  return 'en';
}

/** Get text from a Translations object for a given lang, with fallback */
export function tr(obj: Translations | Record<string, string>, lang: Lang): string {
  return (obj as any)[lang] || obj.en || obj.fr || '';
}

